// ---------------------------------------------------------------------------
// Seed the DB. Idempotent: skips if meta already exists (i.e., first-run
// already completed).
// ---------------------------------------------------------------------------

export async function seedDb(db: LiftLogDb): Promise<void> {
  await db.transaction(
    'rw',
    [
      db.exercises,
      db.planDays,
      db.planItems,
      db.exerciseStates,
      db.mainLifts,
      db.cycleState,
      db.sessions,
      db.setLogs,
      db.guardRails,
      db.milestones,
      db.meta,
    ],
    async () => {
      const existing = await db.meta.get('singleton');
      if (existing) return;

      await db.exercises.bulkPut(EXERCISES);
      await db.planDays.bulkPut(PLAN_DAYS);
      await db.planItems.bulkPut(PLAN_ITEMS);
      await db.exerciseStates.bulkPut(EXERCISE_STATES);
      await db.mainLifts.bulkPut(MAIN_LIFTS);
      await db.cycleState.put(INITIAL_CYCLE_STATE);
      await db.sessions.put(HISTORICAL_SESSION);
      await db.setLogs.bulkPut(HISTORICAL_SET_LOGS);
      await db.guardRails.bulkPut(GUARD_RAILS);
      await db.milestones.bulkPut(MILESTONES);
      await db.meta.put(INITIAL_META);
    },
  );
}
